'''< Crie um programa que imprima na tela os números de 1 a 10.
Utilize uma estrtura de repetição do tipo "for", em um conjunto com a função "range" ()
A invocação da operação de saída não pode imprimir os valores literalmente.
é preciso que o "print" imprima" o conteúdo de alguma variável, dentro do laço, para que a automação faça sentido.>'''

for i in range(1, 11, 1):
    print(i, "", end="")