dado = 16
print(f"O valor inicial da variável é: {dado}")

dado += 1
print(f"Após incrementar em 1, o valor da variável é: {dado}")

dado -= 1
print(f"Após decrementar em 1, o valor da variável é: {dado}")

dado *= 2
print(f"Após duplicar o valor da variável, o valor é: {dado}")

dado /= 2
print(f"Após dividir o valor da variável pela metade, o valor é: {dado}")
