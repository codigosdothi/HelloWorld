## Crie um programa para praticar o uso de variáveis com entrada e saída de dados.
# Declare três váriaveis: idade=0, altura=0.00 e nome="".
# Peça para o usuário informe este dados de uma pessoa e armazene nas respectivas variáveis conforme o estabelecido durante a declaração deles.
# Ao final, informe os dados na tela.

idade = 0
altura = 0.00
nome = ""

idade = int(input("Informe sua idade: "))
altura = float(input("Informe sua altura: "))
nome = input("Informe seu nome: ")

print("Idade digitada: ", idade)
print("Altura digitada: ", altura)
print("Nome digitado: ", nome)


